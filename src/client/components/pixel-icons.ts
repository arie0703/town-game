export type PixelIconName = keyof typeof ICONS;

// assets/icons/ に「アイコン名.拡張子」で置いた画像は、ドット絵の代わりに使う（例: assets/icons/shop.png）
// 手順は docs/icon-assets.md を参照
const imageFiles = import.meta.glob<string>('../../../assets/icons/*.{png,gif,svg,webp}', {
  eager: true,
  query: '?url',
  import: 'default',
});
const IMAGE_OVERRIDES: Partial<Record<string, string>> = Object.fromEntries(
  Object.entries(imageFiles).map(([path, url]) => [path.split('/').pop()!.replace(/\.[^.]+$/, ''), url]),
);

// 同じ色が横に続くピクセルを1つの rect にまとめて SVG にする
function toSvg({ palette, rows }: PixelIcon): string {
  const rects: string[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const char = row[x];
      let end = x + 1;
      while (end < row.length && row[end] === char) end++;
      if (char !== '.') {
        rects.push(`<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${palette[char]}"/>`);
      }
      x = end;
    }
  });
  return `<svg class="pixel-icon" viewBox="0 0 ${SIZE} ${SIZE}" shape-rendering="crispEdges" aria-hidden="true">${rects.join('')}</svg>`;
}

const cache = new Map<PixelIconName, string>();

export function iconHtml(name: PixelIconName): string {
  let html = cache.get(name);
  if (!html) {
    const src = IMAGE_OVERRIDES[name];
    html = src ? `<img class="pixel-icon" src="${src}" alt="" aria-hidden="true" />` : toSvg(ICONS[name]);
    cache.set(name, html);
  }
  return html;
}
